#include <stdio.h>

int main () {
    int a = 10;
    int b = 3;

    printf("a + b 는 : %d \n", a + b);
    printf("a - b 는 : %d \n", a - b);
    printf("a * b 는 : %d \n", a * b);

    // 10 나누기 3의 결과는?
    printf("a / b 는 : %d \n", a / b);

    // 나머지를 구하는 %연산자
    printf("a %% b 는 : %d \n", a % b);
    
    return 0;
}

